    编码格式 (Encoding): Shift-JIS (required for Sekiro compatibility)

    ============================================================================
    功能概述 (Overview):
    ============================================================================
    追击攻击系统是Sekiro AI中用于主动追踪和攻击逃跑或移动敌人的专用模块。
    该系统允许AI在敌人试图拉开距离时快速发动攻击，防止敌人脱离战斗。

    主要功能 (Main Functions):
    - 追击攻击：当敌人移动或逃跑时，AI发动追击性攻击
    - 距离管理：根据成功距离判定攻击是否能够命中
    - 角度限制：支持上下攻击角度限制，适应地形高低差
    - 简化接口：提供简洁的参数配置，快速集成到AI逻辑中

    ============================================================================
    与其他系统的区别 (Differences from Other Systems):
    ============================================================================

    vs. 普通攻击 (Common Attack):
    └─ 追击攻击专注于移动目标，通常具有更长的前冲距离
    └─ 追击攻击的判定更宽松，允许更大的距离误差

    vs. 接近后攻击 (Approach then Attack):
    └─ 追击攻击是单一动作，接近和攻击同时进行
    └─ 接近后攻击分为两个阶段：先接近再攻击

    vs. 连击攻击 (Combo Attack):
    └─ 追击攻击通常是单次攻击，不形成连击序列
    └─ 追击攻击更注重距离弥合而非伤害最大化

    ============================================================================
    参数系统详解 (Parameter System):
    ============================================================================

    参数0: EzStateID - 攻击动画状态编号
    └─ 说明：指定使用哪个攻击动画（通常是带前冲效果的攻击）
    └─ 示例：3000-3999范围通常是普通攻击，某些编号带追击效果
    └─ 设计：追击攻击动画应包含向前移动的动作

    参数1: 攻击对象 (Attack Target)
    └─ 说明：指定追击的目标类型（通常是TARGET_ENE_0，主要敌人）
    └─ 类型：TARGET_ENE_0（玩家）、TARGET_ENE_1（次要敌人）等
    └─ 设计：大多数情况下锁定玩家为追击目标

    参数2: 成功距离 (Success Distance)
    └─ 说明：追击攻击能够成功命中的最大距离（米）
    └─ 范围：通常2-5米，根据攻击动画的前冲距离决定
    └─ 设计：应略大于攻击的实际前冲距离以提供容错空间

    参数3: 上攻击角度 (Upper Attack Angle)
    └─ 说明：允许向上攻击的最大仰角（度）
    └─ 范围：0-90度，0表示不允许向上攻击
    └─ 应用：用于攻击高处的敌人或适应地形高差

    参数4: 下攻击角度 (Lower Attack Angle)
    └─ 说明：允许向下攻击的最大俯角（度）
    └─ 范围：0-90度，0表示不允许向下攻击
    └─ 应用：用于攻击低处的敌人或从高处向下攻击

    ============================================================================
    使用场景 (Use Cases):
    ============================================================================

    场景1: 敌人后退时追击
    └─ 条件：玩家执行后跳或撤退
    └─ 行为：AI发动追击攻击，弥合距离并造成伤害
    └─ 效果：防止玩家轻易脱离战斗

    场景2: 敌人侧移时追击
    └─ 条件：玩家进行侧向移动试图规避
    └─ 行为：AI使用带跟踪效果的追击攻击
    └─ 效果：减少玩家通过走位规避的有效性

    场景3: 高低差地形战斗
    └─ 条件：AI和玩家之间存在高度差
    └─ 行为：利用上下攻击角度参数适应地形
    └─ 效果：确保追击攻击在复杂地形下仍然有效

    ============================================================================
    技术实现细节 (Technical Implementation):
    ============================================================================

    实现原理：
    └─ 直接调用GOAL_COMMON_CommonAttack作为子目标
    └─ 传递特定参数配置追击特性
    └─ 利用通用攻击系统的底层功能

    性能特点：
    └─ 轻量级包装器，开销极小
    └─ 不增加额外的Update循环负担
    └─ 子目标执行完成后自动返回

    设计模式：
    └─ 委托模式：将实际工作委托给CommonAttack
    └─ 参数转换：将简化参数转换为CommonAttack所需格式
    └─ 封装复杂性：隐藏CommonAttack的复杂参数配置
============================================================================]]

