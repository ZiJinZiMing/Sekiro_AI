--[[
追击攻击激活函数 (Pursuit Attack Activation Function)
功能：初始化并启动追击攻击行为
参数：
  f1_arg0 - AI实体对象
  f1_arg1 - 目标参数对象，包含追击配置
返回：无
逻辑流程：
  1. 获取基础追击参数（动画、目标、距离）
  2. 配置追击攻击特性（角度范围、旋转、判定）
  3. 调用通用攻击系统执行追击
设计理念：
  - 简化参数：只暴露5个关键参数，降低使用难度
  - 委托执行：利用成熟的CommonAttack系统
  - 特化配置：针对追击场景优化参数设置
]]
function Pursuit_Activate(f1_arg0, f1_arg1)
    -- ===== 阶段1：获取基础追击参数 (Phase 1: Get Basic Pursuit Parameters) =====
    local f1_local0 = f1_arg1:GetLife()      -- 追击行为的生命周期时间（秒）
    local f1_local1 = f1_arg1:GetParam(0)    -- EzState动画ID：指定追击攻击动画
    local f1_local2 = f1_arg1:GetParam(1)    -- 攻击目标类型：通常是TARGET_ENE_0（玩家）
    local f1_local3 = f1_arg1:GetParam(2)    -- 成功距离：追击攻击的有效距离范围

    -- ===== 阶段2：配置追击攻击特性 (Phase 2: Configure Pursuit Attack Characteristics) =====
    -- 这些参数针对追击场景进行了优化，确保追击攻击的有效性和流畅性

    local f1_local4 = 180     -- 攻击角度范围：180度（半圆）
                              -- 理由：追击攻击需要较宽的判定角度以应对移动目标
                              -- 效果：即使目标侧向移动，仍可能命中

    local f1_local5 = 0       -- 攻击前旋转时间：0秒（即时攻击）
                              -- 理由：追击强调速度，不给敌人额外反应时间
                              -- 效果：AI决定追击后立即发动，最小化延迟

    local f1_local6 = 90      -- 正面判定角度：90度（前方扇形区域）
                              -- 理由：追击攻击主要针对前方移动的目标
                              -- 效果：确保攻击判定合理，不会打到背后的目标

    -- ===== 阶段3：配置追击行为标志 (Phase 3: Configure Pursuit Behavior Flags) =====
    -- 这些布尔标志控制追击攻击的具体表现

    local f1_local7 = true    -- 启用追击特性：确保攻击带有追踪效果
                              -- 效果：攻击动画会尝试跟随目标位置

    local f1_local8 = false   -- 禁用连击取消：追击通常是单次攻击
                              -- 理由：追击攻击完成后应重新评估形势
                              -- 效果：防止AI盲目连续追击导致过度激进

    local f1_local9 = true    -- 启用目标跟踪：持续锁定目标方向
                              -- 效果：攻击过程中AI会调整朝向以跟随目标

    local f1_local10 = false  -- 禁用复杂检查：简化追击逻辑以提高响应速度
                              -- 理由：追击强调快速反应，复杂检查会增加延迟
                              -- 效果：追击决策更加果断

    local f1_local11 = false  -- 非连击模式：追击是独立攻击，不是连击的一部分
                              -- 理由：追击通常在普通连击序列之外使用
                              -- 效果：追击完成后返回正常战斗循环

    -- ===== 阶段4：获取角度限制参数 (Phase 4: Get Angle Limit Parameters) =====
    -- 这些参数使追击攻击能够适应地形高低差

    local f1_local12 = f1_arg1:GetParam(3)   -- 上攻击角度：允许向上攻击的最大仰角
                                             -- 应用：攻击高处平台上的敌人
                                             -- 典型值：30-45度

    local f1_local13 = f1_arg1:GetParam(4)   -- 下攻击角度：允许向下攻击的最大俯角
                                             -- 应用：从高处向下追击敌人
                                             -- 典型值：30-45度

    -- ===== 阶段5：启动通用攻击子目标 (Phase 5: Start Common Attack Sub-goal) =====
    -- 将所有配置好的参数传递给通用攻击系统，执行实际的追击攻击
    -- 参数顺序必须严格匹配CommonAttack的接口定义
    f1_arg1:AddSubGoal(
        GOAL_COMMON_CommonAttack,    -- 目标类型：通用攻击系统
        f1_local0,                    -- 生命周期：控制攻击的持续时间
        f1_local1,                    -- 动画ID：追击攻击的动画
        f1_local2,                    -- 目标类型：追击的目标
        f1_local3,                    -- 成功距离：判定攻击成功的距离
        f1_local4,                    -- 攻击角度范围：180度宽判定
        f1_local5,                    -- 旋转时间：0秒即时攻击
        f1_local6,                    -- 正面角度：90度前方判定
        f1_local8,                    -- 连击取消：禁用
        f1_local9,                    -- 目标跟踪：启用
        f1_local10,                   -- 复杂检查：禁用
        f1_local11,                   -- 连击模式：禁用
        f1_local12,                   -- 上攻击角度：地形适应
        f1_local13,                   -- 下攻击角度：地形适应
        f1_local7                     -- 追击特性：启用
    )

end

