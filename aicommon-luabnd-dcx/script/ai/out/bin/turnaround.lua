    ◆ 参数配置建议 (Parameter Configuration Recommendations):
    ──────────────────────────────────────────────────────────────────────

    【精确定位配置】- 需要精确到达特定位置
    ├─ 角度阈值：5-10度（高精度）
    ├─ 生命周期：10秒（给予充足时间）
    ├─ 超时成功：0（确保精确完成）
    └─ 移动类型：1步行（更易控制）

    【快速机动配置】- 强调速度而非精确性
    ├─ 角度阈值：20-30度（低精度）
    ├─ 生命周期：3-5秒（快速决策）
