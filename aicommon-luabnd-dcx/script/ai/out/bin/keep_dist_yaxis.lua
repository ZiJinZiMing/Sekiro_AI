--[[============================================================================
    keep_dist_yaxis.lua - Y轴距离保持系统 (Y-Axis Distance Maintenance System)

    版本信息 (Version Info): v2.0 - Enhanced with comprehensive annotations
    作者 (Author): FromSoftware AI Team / Enhanced by Claude Code
    最后修改 (Last Modified): 2025-10-14
    编码格式 (Encoding): Shift-JIS (required for Sekiro compatibility)

    ============================================================================
    功能概述 (Overview):
    ============================================================================
    Y轴距离保持系统是Sekiro AI中用于管理垂直高度关系的专用模块。该系统
    允许AI在有高低差的地形上调整自身的垂直位置，确保与目标保持在合适的
    高度范围内，从而能够有效地进行攻击和防御。

    主要功能 (Main Functions):
    - 垂直距离监控：实时检测AI与目标的高度差
    - 自动高度调整：通过特殊动作调整垂直位置
    - 双向调整能力：支持向上和向下两个方向的调整
    - 朝向锁定：在调整过程中持续面向目标
    - 状态管理：追踪调整进度和完成状态

    ============================================================================
    核心概念：带符号的Y轴距离 (Core Concept: Signed Y-Axis Distance)
    ============================================================================

    GetDistYSigned() 函数说明：
    └─ 返回AI相对于目标的垂直距离（带符号）
    └─ 正值：AI在目标上方（AI更高）
    └─ 负值：AI在目标下方（AI更低）
    └─ 零值：AI与目标处于相同高度

    示例场景：
    ┌─────────────────────────────────────────┐
    │ 情况1：AI在高处，目标在低处              │
    │    AI (高度10米)                        │
    │     ↓ 5米高度差                         │
    │    Target (高度5米)                     │
    │ GetDistYSigned() = +5                   │
    │ 解读：AI需要向下移动才能接近目标        │
    └─────────────────────────────────────────┘

    ┌─────────────────────────────────────────┐
    │ 情况2：AI在低处，目标在高处              │
    │    Target (高度10米)                    │
    │     ↓ 5米高度差                         │
    │    AI (高度5米)                         │
    │ GetDistYSigned() = -5                   │
    │ 解读：AI需要向上移动才能接近目标        │
    └─────────────────────────────────────────┘

    ============================================================================
    参数系统详解 (Parameter System):
    ============================================================================

    参数0: ターゲット (Target)
    └─ 说明：指定用于高度比较的目标对象
    └─ 类型：TARGET_ENE_0（主要敌人）、TARGET_SELF（自身）等
    └─ 设计：通常使用TARGET_ENE_0，与玩家保持合适高度

    参数1: 最低距離 (Minimum Distance)
    └─ 说明：允许的最小高度差（米）
    └─ 含义：当实际高度差小于此值时，AI需要调整
    └─ 示例：-3表示AI可以在目标下方3米内
    └─ 设计：定义"太接近"的阈值

    参数2: 最大距離 (Maximum Distance)
    └─ 说明：允许的最大高度差（米）
    └─ 含义：当实际高度差大于此值时，AI需要调整
    └─ 示例：+3表示AI可以在目标上方3米内
    └─ 设计：定义"太远离"的阈值

    参数3: 朝向目标 (Face Target)
    └─ 说明：指定AI在调整过程中应面向的目标
    └─ 类型：通常与参数0相同
    └─ 设计：确保AI在调整高度时保持战斗姿态

    距离范围解析：
    ┌──────────────────────────────────────────────┐
    │  参数1 (最小)    理想区域    参数2 (最大)    │
    │     ↓              ↓              ↓          │
    │   -3米  ←── [合适范围] ──→  +3米           │
    │                                              │
    │  AI太低          正好        AI太高         │
    │  需上移       无需调整       需下移          │
    └──────────────────────────────────────────────┘

    ============================================================================
    特殊动作说明 (Special Action IDs):
    ============================================================================

    动作705：向上调整动作
    └─ 触发条件：AI高度低于最小距离阈值
    └─ 效果：AI执行向上移动/攀爬动作
    └─ 应用：爬坡、跳跃、攀爬等垂直移动
    └─ 设计：动画应包含向上的位移

    动作706：向下调整动作
    └─ 触发条件：AI高度高于最大距离阈值
    └─ 效果：AI执行向下移动/降落动作
    └─ 应用：下坡、跳下、降落等垂直移动
    └─ 设计：动画应包含向下的位移

    ============================================================================
    状态管理系统 (State Management System):
    ============================================================================

    Number(0) 状态标志说明：
    ├─ 状态0：未在目标高度范围内，正在调整
    ├─ 状态1：已进入目标高度范围，等待攻击完成
    └─ 状态2：初始就在目标高度范围内（快速成功）

    状态转换流程：
    ┌────────────────────────────────────────────┐
    │ 激活时检查                                  │
    │   ↓                                         │
    │ 在范围内? ──是→ 状态2 → 立即成功          │
    │   ↓否                                       │
    │ 状态0（开始调整）                          │
    │   ↓                                         │
    │ 更新检查                                    │
    │   ↓                                         │
    │ 进入范围? ──是→ 状态1（等待攻击）        │
    │   ↓否                                       │
    │ 继续调整（触发705或706）                  │
    │   ↓                                         │
    │ 状态1 且 无攻击阻碍? ──是→ 成功           │
    └────────────────────────────────────────────┘

    ============================================================================
    使用场景 (Use Cases):
    ============================================================================

    场景1: 高处敌人向下攻击
    └─ 条件：AI在高台，玩家在低处
    └─ 行为：保持在玩家上方一定高度范围
    └─ 效果：发动俯冲攻击或远程攻击

    场景2: 低处敌人向上攻击
    └─ 条件：AI在低处，玩家在高台
    └─ 行为：尝试爬升到合适高度
    └─ 效果：缩小高度差，进行有效攻击

    场景3: 飞行敌人高度控制
    └─ 条件：AI具有飞行能力
    └─ 行为：动态调整飞行高度
    └─ 效果：保持在玩家攻击范围边缘

    场景4: 多层地形战斗
    └─ 条件：战场有多个高度层次
    └─ 行为：根据战术需要调整所在层次
    └─ 效果：利用地形优势进行攻击

    ============================================================================
    技术实现细节 (Technical Implementation):
    ============================================================================

    更新频率：0.5-0.6秒
    └─ 比一般目标更慢的更新频率
    └─ 理由：高度调整通常需要较长时间的动画
    └─ 效果：减少不必要的重复检查

    攻击集成：
    └─ 使用SetAttackRequest()而非AddSubGoal()
    └─ 理由：705/706是移动性攻击，不是独立目标
    └─ 效果：高度调整和攻击动作融合

    取消机制：
    └─ 检查IsEnableCancelMove()
    └─ 允许在合适时机取消调整动作
    └─ 防止AI被困在无法完成的调整中
============================================================================]]

-- 注册目标更新时间：每0.5-0.6秒更新一次
-- 高度调整通常需要较长动画，不需要频繁检查
REGISTER_GOAL_UPDATE_TIME(GOAL_COMMON_KeepDistYAxis, 0.5, 0.6)

--[[
Y轴距离保持激活函数 (Y-Axis Distance Keep Activation Function)
功能：初始化Y轴距离保持行为，检查初始高度
参数：
  f1_arg0 - AI实体对象
  f1_arg1 - 目标参数对象
返回：无
逻辑流程：
  1. 初始化状态标志为0（未在目标范围）
  2. 设置朝向目标
  3. 获取当前垂直距离
  4. 检查是否已在目标范围内
  5. 如果已在范围内，标记为状态2（快速成功）
设计理念：
  - 初始检查：避免不必要的调整
  - 快速通道：已在范围内则立即完成
  - 状态初始化：为Update函数准备状态
]]
function KeepDistYAxis_Activate(f1_arg0, f1_arg1)
    -- ===== 阶段1：状态初始化 (Phase 1: State Initialization) =====
    -- 设置状态标志为0：表示"尚未在目标高度范围内"
    -- 这个标志将在Update函数中用于追踪调整进度
    f1_arg1:SetNumber(0, 0)

    -- ===== 阶段2：朝向设置 (Phase 2: Orientation Setup) =====
    -- 获取朝向目标参数并设置AI朝向
    -- 确保AI在调整高度时保持面向目标
    local f1_local0 = f1_arg1:GetParam(3)  -- 朝向目标类型
    f1_arg0:TurnTo(f1_local0)              -- 设置朝向

    -- ===== 阶段3：获取高度参数 (Phase 3: Get Height Parameters) =====
    local f1_local1 = f1_arg1:GetParam(0)   -- 高度比较目标
    -- 获取带符号的垂直距离：正值=AI更高，负值=AI更低
    local f1_local2 = f1_arg0:GetDistYSigned(f1_local1)

    local f1_local3 = f1_arg1:GetParam(1)   -- 最小距离阈值
    local f1_local4 = f1_arg1:GetParam(2)   -- 最大距离阈值

    -- ===== 阶段4：初始范围检查 (Phase 4: Initial Range Check) =====
    -- 检查当前高度是否已在目标范围内
    -- 条件：最小距离 <= -实际距离 <= 最大距离
    -- 注意：使用负号是因为GetDistYSigned的符号约定
    --       当AI在目标下方时，GetDistYSigned返回负值
    --       我们需要检查|AI高度 - 目标高度|是否在范围内
    if f1_local3 <= -f1_local2 and -f1_local2 <= f1_local4 then
        -- 已经在目标高度范围内！
        -- 设置状态2：表示"初始就在范围内，无需调整"
        f1_arg1:SetNumber(0, 2)
        -- 这将导致Update函数在第一次调用时立即返回成功
    end
    -- 如果不在范围内，状态保持为0，Update函数将开始调整过程

end

--[[
Y轴距离保持更新函数 (Y-Axis Distance Keep Update Function)
功能：每0.5-0.6秒检查一次高度状态，触发调整动作
参数：
  f2_arg0 - AI实体对象
  f2_arg1 - 目标参数对象
返回：
  GOAL_RESULT_Success - 高度调整完成
  GOAL_RESULT_Continue - 继续调整
逻辑流程：
  1. 快速成功检查（状态2）
  2. 更新朝向
  3. 获取当前高度
  4. 检查是否进入目标范围
  5. 检查攻击状态
  6. 触发相应的调整动作
设计理念：
  - 多路径决策：根据不同高度情况选择动作
  - 攻击协调：等待攻击完成后再判定成功
  - 持续调整：未在范围内时重复触发调整
]]
function KeepDistYAxis_Update(f2_arg0, f2_arg1)
    -- ===== 阶段1：快速成功路径 (Phase 1: Fast Success Path) =====
    -- 检查状态标志是否为2（初始就在目标范围）
    -- 这是最优化的路径，无需任何调整直接成功
    if f2_arg1:GetNumber(0) == 2 then
        return GOAL_RESULT_Success  -- 立即返回成功
    end

    -- ===== 阶段2：持续朝向更新 (Phase 2: Continuous Orientation Update) =====
    -- 获取朝向目标并持续更新AI朝向
    -- 这确保AI在整个调整过程中保持面向目标
    local f2_local0 = f2_arg1:GetParam(3)  -- 朝向目标
    f2_arg0:TurnTo(f2_local0)              -- 更新朝向

    -- ===== 阶段3：获取当前高度状态 (Phase 3: Get Current Height State) =====
    local f2_local1 = f2_arg1:GetParam(0)   -- 高度比较目标
    -- 获取当前的带符号垂直距离
    local f2_local2 = f2_arg0:GetDistYSigned(f2_local1)

    local f2_local3 = f2_arg1:GetParam(1)   -- 最小距离阈值
    local f2_local4 = f2_arg1:GetParam(2)   -- 最大距离阈值

    -- ===== 阶段4：范围检查与状态更新 (Phase 4: Range Check & State Update) =====
    -- 检查当前高度是否进入目标范围
    if f2_local3 <= -f2_local2 and -f2_local2 <= f2_local4 then
        -- 进入目标高度范围！
        -- 设置状态1：表示"已在范围内，但需等待攻击完成"
        f2_arg1:SetNumber(0, 1)
        -- 为什么不立即返回成功？
        -- 因为AI可能正在执行调整动作（705或706），
        -- 需要等待动作完成才能判定最终成功
    end

    -- ===== 阶段5：攻击状态检查与完成判定 (Phase 5: Attack State & Completion Check) =====
    -- 检查AI是否正在执行攻击，或攻击是否可被移动取消
    -- 这两个条件确保AI可以安全地结束或继续调整
    if f2_arg0:IsStartAttack() == false or f2_arg0:IsEnableCancelMove() then
        -- 子条件1：已在目标范围内（状态非0）
        if f2_arg1:GetNumber(0) ~= 0 then
            -- 条件满足：已在范围内且无攻击阻碍
            -- 重置状态标志并返回成功
            f2_arg1:SetNumber(0, 0)     -- 清理状态
            return GOAL_RESULT_Success  -- 任务完成！

        -- 子条件2：当前高度低于最小阈值（AI太低，需要上升）
        elseif -f2_local2 < f2_local3 then
            -- 触发向上调整动作
            -- 动作705：向上移动/攀爬/跳跃
            f2_arg0:SetAttackRequest(705)
            -- 注意：使用SetAttackRequest而非AddSubGoal
            -- 因为705是移动性动作，与当前目标并行执行

        -- 子条件3：当前高度高于最大阈值（AI太高，需要下降）
        elseif f2_local4 < -f2_local2 then
            -- 触发向下调整动作
            -- 动作706：向下移动/降落/跳下
            f2_arg0:SetAttackRequest(706)
            -- 这个动作会让AI向下调整高度
        end
        -- 如果在范围内，且没有特殊状态，继续等待
    end
    -- 如果正在攻击且无法取消，则保持当前状态不触发新动作

    -- ===== 阶段6：继续执行 (Phase 6: Continue Execution) =====
    -- 所有完成条件都不满足，继续保持目标活跃
    return GOAL_RESULT_Continue

end

--[[
Y轴距离保持终止函数 (Y-Axis Distance Keep Termination Function)
功能：清理Y轴距离保持相关状态
参数：
  f3_arg0 - AI实体对象
