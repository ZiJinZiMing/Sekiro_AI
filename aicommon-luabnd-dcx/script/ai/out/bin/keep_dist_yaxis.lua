  - 自动清理：依赖系统自动清理机制
  - 无副作用：高度调整不会留下持久状态
  - 简洁设计：避免不必要的手动清理代码
]]
function KeepDistYAxis_Terminate(f3_arg0, f3_arg1)
    -- 空实现：Y轴距离保持无需特殊终止处理
    -- 调整动作会自动完成或取消
    -- 状态标志会随目标销毁而清除

end

-- 注册该目标为不可中断类型 (Register as Non-interruptible Goal)
-- 理由：高度调整是战术定位的基础，中断会导致高度混乱
-- 效果：确保AI的高度调整能够完整执行
REGISTER_GOAL_NO_INTERUPT(GOAL_COMMON_KeepDistYAxis, true)

--[[
Y轴距离保持中断处理函数 (Y-Axis Distance Keep Interrupt Handler)
功能：决定是否允许其他目标中断当前高度调整
参数：
  f4_arg0 - AI实体对象
  f4_arg1 - 目标参数对象
返回：false - 不允许中断，确保高度调整的完整性
逻辑：
  高度调整是三维战斗的基础，中断会导致AI无法有效攻击
  完整的高度调整对在复杂地形上的战斗至关重要
设计理念：
  - 三维战斗完整性：确保AI在正确的高度层次
  - 地形适应性：允许AI充分利用地形优势
  - 系统稳定：避免因频繁中断导致高度错乱
性能考虑：
  - 简单返回false，零计算开销
  - 不涉及任何状态检查或复杂逻辑
]]
function KeepDistYAxis_Interupt(f4_arg0, f4_arg1)
    -- 始终返回false，不允许中断Y轴距离保持
    -- 确保AI能够调整到合适的战斗高度
    return false

end

