--[[----------------------------------------------------------------------------
函数名: DS2PGTest14000_Battle_Activate
功能: 激活测试AI的战斗行为

参数说明:
    f1_arg0 - AI实例对象，提供AI状态查询和操作接口
    f1_arg1 - Goal管理器，用于添加和管理AI子目标

处理流程:
    1. 检测与敌人的距离
    2. 如果距离小于1米：执行普通右手攻击组合
    3. 如果距离大于等于1米：接近目标

技术细节:
    - NPC_ATK_NormalR: 普通右手攻击动作ID
    - 攻击距离限制为3米
    - 接近目标时不使用行走模式（false参数）
    - 接近目标时不使用特定动画（-1参数）
----------------------------------------------------------------------------]]--
function DS2PGTest14000_Battle_Activate(f1_arg0, f1_arg1)
    -- 距离判定：小于1米时执行攻击
    if f1_arg0:GetDist(TARGET_ENE_0) < 1 then
        -- 添加连击目标：持续10秒，使用普通右手攻击，目标距离3米
        f1_arg1:AddSubGoal(GOAL_COMMON_ComboAttack, 10, NPC_ATK_NormalR, TARGET_ENE_0, 3, 0)
    else
        -- 距离太远时接近目标：持续10秒，不使用行走模式
        f1_arg1:AddSubGoal(GOAL_COMMON_ApproachTarget, 10, TARGET_ENE_0, AI_DIR_TYPE_CENTER, TARGET_SELF, false, -1)
    end

end

--[[----------------------------------------------------------------------------
函数名: DS2PGTest14000_Battle_Update
功能: 更新战斗状态，判断是否应该退出战斗

参数说明:
    f2_arg0 - AI实例对象
    f2_arg1 - Goal管理器

返回值:
    GOAL_RESULT_Success - 战斗结束（距离过远）
    GOAL_RESULT_Continue - 继续战斗

处理逻辑:
    检测敌人距离，如果超过20米则退出战斗状态
----------------------------------------------------------------------------]]--
function DS2PGTest14000_Battle_Update(f2_arg0, f2_arg1)
    -- 距离超过20米时结束战斗Goal
    if f2_arg0:GetDist(TARGET_ENE_0) > 20 then
        return GOAL_RESULT_Success
    end
    -- 否则继续执行当前战斗行为
    return GOAL_RESULT_Continue

end

